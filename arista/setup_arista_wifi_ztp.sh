# ──────────────────────────────────────────────
# Validation
# ──────────────────────────────────────────────
validate_ipv4() {
    local ip="$1"
    local IFS='.'
    read -ra octets <<< "$ip"
    [[ ${#octets[@]} -ne 4 ]] && return 1
    for octet in "${octets[@]}"; do
        [[ ! "$octet" =~ ^[0-9]+$ ]] && return 1
        (( octet < 0 || octet > 255 )) && return 1
    done
    return 0
}

validate_ipv6() {
    local ip="$1"
    [[ "$ip" =~ ^([0-9a-fA-F]{0,4}:){1,7}[0-9a-fA-F]{0,4}$ ]] || \
    [[ "$ip" =~ ^([0-9a-fA-F]{0,4}:){1,6}:[0-9a-fA-F]{0,4}$ ]] || \
    [[ "$ip" =~ :: ]]
}

validate_cidr_v4() {
    local cidr="$1"
    [[ "$cidr" =~ ^([0-9]+\.[0-9]+\.[0-9]+\.[0-9]+)/([0-9]+)$ ]] || return 1
    local ip="${BASH_REMATCH[1]}"
    local prefix="${BASH_REMATCH[2]}"
    validate_ipv4 "$ip" || return 1
    (( prefix < 0 || prefix > 32 )) && return 1
    return 0
}

validate_cidr_v6() {
    local cidr="$1"
    [[ "$cidr" =~ ^(.+)/([0-9]+)$ ]] || return 1
    local prefix="${BASH_REMATCH[2]}"
    (( prefix < 0 || prefix > 128 )) && return 1
    return 0
}

validate_netmask() {
    validate_ipv4 "$1" || return 1
    local IFS='.'
    read -ra o <<< "$1"
    local n=$(( (o[0] << 24) + (o[1] << 16) + (o[2] << 8) + o[3] ))
    local inv=$(( ~n & 0xFFFFFFFF ))
    (( (inv & (inv + 1)) == 0 )) && return 0
    return 1
}

# ──────────────────────────────────────────────
# CIDR Auto-Derivation (IPv4)
# ──────────────────────────────────────────────
cidr_to_netmask() {
    local prefix="$1"
    local mask=$(( 0xFFFFFFFF << (32 - prefix) & 0xFFFFFFFF ))
    printf "%d.%d.%d.%d" \
        $(( (mask >> 24) & 0xFF )) \
        $(( (mask >> 16) & 0xFF )) \
        $(( (mask >> 8)  & 0xFF )) \
        $(( mask & 0xFF ))
}

suggest_range() {
    local network="$1"
    local IFS='.'
    read -ra octets <<< "${network%%/*}"
    local base="${octets[0]}.${octets[1]}.${octets[2]}"
    echo "${base}.100 ${base}.200"
}

suggest_gateway() {
    local network="$1"
    local IFS='.'
    read -ra octets <<< "${network%%/*}"
    printf "%s.%s.%s.1" "${octets[0]}" "${octets[1]}" "${octets[2]}"
}

# ──────────────────────────────────────────────
# Config Generator (replaces Jinja2 template)
# ──────────────────────────────────────────────
generate_config() {
    local network_addr="${NETWORK%%/*}"

    cat <<EOF
###################
# isc-dhcp-server #
###################
# Generated by setup_arista_wifi_ztp.sh
# Author: benedikt@arista.com
# ISC DHCP Configuration for Arista ZTP
# CV-CUE Server: ${CVCUE}
#
EOF

    if [[ "$IPVERSION" == "6" ]]; then
        cat <<'EOF'
# For testing w/o Arista AP see isc-dhcp6-ap-client6.conf
# Doc: https://www.arista.com/en/ug-cv-cue/cv-cue-dhcp-ipv6-server-discovery-by-arista-access-points
#
# The RA from the router residing in AP NETWORK need to contain:
#   ipv6 nd other-config-flag
#   ipv6 nd managed-config-flag
#
# DHCPv6 Option 16 (We want to match on):
#   Byte 0-3:  Enterprise Number (4 bytes)  →  \x00\x00\x42\x05  (16901) (Arista)
#   Byte 4-5:  Data Length (2 bytes)         →  \x00\x0f          (15)
#   Byte 6-20: VCI String (15 bytes)         →  ARISTA-AP-C-430
# As we want only VCI, we need "substring" with offset 6 and taking 15 bytes
#
# DHCPv6 Option 17 (We want to return):
#   Byte 0-3:   Enterprise Number (4 bytes)   →  \x00\x00\x42\x05  (16901) (Arista)
#   Byte 4-5:   Sub-option 1 Code (2 bytes)   →  \x00\x01          (Server Address)
#   Byte 6-7:   Sub-option 1 Length (2 bytes)  →  \x00\x16          (22)
#   Byte 8-29:  Sub-option 1 Data (22 bytes)   →  fd12:3456:789a:40::100
#   Byte 30-31: Sub-option 4 Code (2 bytes)    →  \x00\x04          (Magic String)
#   Byte 32-33: Sub-option 4 Length (2 bytes)   →  \x00\x0b          (11)
#   Byte 34-44: Sub-option 4 Data (11 bytes)    →  SPECTRATALK
# To generate this byte string you can use isc-dhcp6-generate_option17.py
EOF
    fi

    cat <<'EOF'

# General
authoritative;
default-lease-time 3600;
preferred-lifetime 3600;
option dhcp-renewal-time 3600;
option dhcp-rebinding-time 7200;
EOF

    if [[ "$IPVERSION" == "4" ]]; then
        cat <<EOF

# Arista AP Onboarding

option space arista;
option arista.cv-cue-server code 1 = text;
option arista.magic-string code 4 = text;

class "Arista-AP" {
    match if option vendor-class-identifier ~= "${MATCHSTRING}";
    vendor-option-space arista;
    option arista.cv-cue-server "${CVCUE}";
    option arista.magic-string "SPECTRATALK";
}
EOF

        if [[ -n "$TFTP" ]]; then
            cat <<EOF

class "Arista-CCS" {
    match if substring(option vendor-class-identifier, 0, 6) = "Arista";
    option bootfile-name "http://${TFTP}/ztp.conf";
}

EOF
        fi

        cat <<EOF

subnet ${network_addr} netmask ${NETMASK} {
    range ${RANGESTART} ${RANGEEND};
    option routers ${GATEWAY};
    option domain-name-servers ${NAMESERVER};
}
EOF
    fi

    if [[ "$IPVERSION" == "6" ]]; then
        cat <<EOF

# Define the DHCPv6 Option 16 (Vendor)
option space ARISTA_AP;
option ARISTA_AP.device_management_address code 1 = string;
option ARISTA_AP.magic code 4 = string;
option dhcp6.vendor-opts code 17 = encapsulate ARISTA_AP;

# Define search domain and dns
option dhcp6.domain-search "aristanetworks.com, sjc.aristanetworks.com, pune.aristanetworks.com.";
option dhcp6.name-servers ${NAMESERVER};

subnet6 ${NETWORK} {
  range6 ${network_addr}100 ${network_addr}200;

  if substring(option dhcp6.vendor-class, 6, 15) ~= "${MATCHSTRING}" {
    option dhcp6.vendor-opts "${MAGICSTRING}";
    option dhcp6.bootfile-url "my-startup-config";
  }
}
EOF
    fi
}

