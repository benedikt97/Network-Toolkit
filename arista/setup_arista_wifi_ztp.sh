# ──────────────────────────────────────────────
# Interactive Prompts
# ──────────────────────────────────────────────
prompt_value() {
    local prompt_text="$1"
    local default_val="$2"
    local var_name="$3"
    local validator="$4"
    local required="${5:-true}"

    while true; do
        if [[ -n "$default_val" ]]; then
            echo -en "  ${BOLD}${prompt_text}${RESET} ${DIM}[${default_val}]${RESET}: "
        else
            echo -en "  ${BOLD}${prompt_text}${RESET}: "
        fi

        local input
        read -r input

        if [[ -z "$input" && -n "$default_val" ]]; then
            input="$default_val"
        fi

        if [[ -z "$input" && "$required" == "true" ]]; then
            print_error "This field is required."
            continue
        fi

        if [[ -n "$validator" && -n "$input" ]]; then
            if ! $validator "$input"; then
                print_error "Invalid format. Please try again."
                continue
            fi
        fi

        eval "export $var_name=\"$input\""
        return 0
    done
}

prompt_choice() {
    local prompt_text="$1"
    local options="$2"
    local default_val="$3"
    local var_name="$4"

    while true; do
        echo -en "  ${BOLD}${prompt_text}${RESET} ${DIM}(${options})${RESET} ${DIM}[${default_val}]${RESET}: "
        local input
        read -r input
        [[ -z "$input" ]] && input="$default_val"

        if [[ "$options" == *"$input"* ]]; then
            eval "export $var_name=\"$input\""
            return 0
        fi
        print_error "Please choose one of: ${options}"
    done
}

print_summary() {
    echo ""
    echo -e "${BOLD}${CYAN}┌─────────────────────────────────────────────┐${RESET}"
    echo -e "${BOLD}${CYAN}│           Configuration Summary             │${RESET}"
    echo -e "${BOLD}${CYAN}└─────────────────────────────────────────────┘${RESET}"
    echo ""

    local label_width=20
    print_row() {
        printf "  ${BOLD}%-${label_width}s${RESET} %s\n" "$1" "$2"
    }

    print_row "Mode:" "$MODE"
    print_row "IP Version:" "IPv${IPVERSION}"
    print_row "Network:" "$NETWORK"

    if [[ "$IPVERSION" == "4" ]]; then
        print_row "Netmask:" "$NETMASK"
        print_row "Gateway:" "$GATEWAY"
        print_row "DHCP Range:" "${RANGESTART} - ${RANGEEND}"
    fi

    print_row "Nameserver:" "$NAMESERVER"
    print_row "CV-CUE Server:" "$CVCUE"

    if [[ -n "$MATCHSTRING" ]]; then
        print_row "VCI Match:" "$MATCHSTRING"
    fi
    if [[ -n "$TFTP" ]]; then
        print_row "TFTP Server:" "$TFTP"
    fi
    echo ""
}

interactive_setup() {
    banner

    # --- Step 1: Mode ---
    print_header "Step 1: What would you like to do?"
    echo ""
    echo -e "  ${GREEN}generate${RESET}  Generate DHCP config and print to stdout"
    echo -e "  ${YELLOW}install${RESET}   Generate, write to disk, and restart isc-dhcp-server ${DIM}(Ubuntu only)${RESET}"
    echo -e "  ${CYAN}test${RESET}      Test DHCP and DNS connectivity on an existing setup"
    echo ""
    prompt_choice "Mode" "generate/install/test" "generate" "MODE"
    echo ""

    # --- Step 2: IP Version ---
    print_header "Step 2: IP Version"
    echo ""
    prompt_choice "Which IP version?" "4/6" "4" "IPVERSION"
    echo ""

    # --- Test mode: only needs interface ---
    if [[ "$MODE" == "test" ]]; then
        print_header "Step 3: Test Interface"
        echo ""
        prompt_value "Network interface to test on (e.g. ens18, eth0)" "" "INTERFACE"
        echo ""

        echo -en "  ${BOLD}Run test?${RESET} ${DIM}[Y/n]${RESET}: "
        read -r confirm
        if [[ "$confirm" =~ ^[Nn] ]]; then
            print_warn "Aborted."
            exit 0
        fi
        return
    fi

    # --- Step 3: Network Configuration ---
    print_header "Step 3: Network Configuration"
    echo ""

    if [[ "$IPVERSION" == "4" ]]; then
        prompt_value "Subnet (CIDR notation, e.g. 192.168.10.0/24)" "" "NETWORK" "validate_cidr_v4"

        local prefix="${NETWORK##*/}"
        local auto_netmask
        auto_netmask=$(cidr_to_netmask "$prefix")
        local range
        range=$(suggest_range "$NETWORK")
        local auto_range_start="${range% *}"
        local auto_range_end="${range#* }"
        local auto_gateway
        auto_gateway=$(suggest_gateway "$NETWORK")

        echo ""
        print_info "Auto-derived from /${prefix}:"
        print_info "  Netmask:    ${auto_netmask}"
        print_info "  Gateway:    ${auto_gateway}"
        print_info "  Range:      ${auto_range_start} - ${auto_range_end}"
        echo ""

        prompt_value "Netmask" "$auto_netmask" "NETMASK" "validate_netmask"
        prompt_value "Default gateway" "$auto_gateway" "GATEWAY" "validate_ipv4"
        prompt_value "DHCP range start" "$auto_range_start" "RANGESTART" "validate_ipv4"
        prompt_value "DHCP range end" "$auto_range_end" "RANGEEND" "validate_ipv4"

    elif [[ "$IPVERSION" == "6" ]]; then
        prompt_value "Subnet (CIDR notation, e.g. fd12:100:100:40::/64)" "" "NETWORK" "validate_cidr_v6"
    fi

    # --- Step 4: Services ---
    echo ""
    print_header "Step 4: Services"
    echo ""

    if [[ "$IPVERSION" == "4" ]]; then
        prompt_value "DNS nameserver" "" "NAMESERVER" "validate_ipv4"
    else
        prompt_value "DNS nameserver" "" "NAMESERVER" "validate_ipv6"
    fi

    echo ""
    echo -e "  ${DIM}Tip: Enter ${YELLOW}cloud${DIM} to use Arista's cloud redirector${RESET}"
    prompt_value "CV-CUE server address" "" "CVCUE"

    if [[ "$IPVERSION" == "4" ]]; then
        local default_match="ARISTA-AP*"
    else
        local default_match="ARISTA-AP-C-*"
    fi
    prompt_value "VCI match pattern" "$default_match" "MATCHSTRING"

    if [[ "$IPVERSION" == "4" ]]; then
        echo ""
        print_info "Optional: TFTP server for CCS/DCS device boot (leave empty to skip)"
        prompt_value "TFTP server" "" "TFTP" "" "false"
    fi

    # --- Resolve cloud shortcut ---
    if [[ "$CVCUE" == "cloud" ]]; then
        export CVCUE="redirector.online.spectraguard.net"
    fi

    # --- Summary ---
    print_summary

    echo -en "  ${BOLD}Proceed?${RESET} ${DIM}[Y/n]${RESET}: "
    read -r confirm
    if [[ "$confirm" =~ ^[Nn] ]]; then
        echo ""
        print_warn "Aborted."
        exit 0
    fi
    echo ""
}

# ──────────────────────────────────────────────
# Flag Parsing
# ──────────────────────────────────────────────
MODE="generate"
INTERACTIVE=false

if [[ $# -eq 0 ]]; then
    INTERACTIVE=true
fi

while [[ $# -gt 0 ]]; do
    case $1 in
        -devicetype | --devicetype )
            export TYPE="$2"
            shift 2 ;;
        -ipversion | --ipversion )
            export IPVERSION="$2"
            shift 2 ;;
        -network | --network )
            export NETWORK="$2"
            shift 2 ;;
        -range-begin | --range-begin )
            export RANGESTART="$2"
            shift 2 ;;
        -range-end | --range-end )
            export RANGEEND="$2"
            shift 2 ;;
        -netmask | --netmask )
            export NETMASK="$2"
            shift 2 ;;
        -gateway | --gateway )
            export GATEWAY="$2"
            shift 2 ;;
        -nameserver | --nameserver )
            export NAMESERVER="$2"
            shift 2 ;;
        -cvcue | --cvcue )
            export CVCUE="$2"
            shift 2 ;;
        -mode | --mode )
            MODE="$2"
            shift 2 ;;
        -interface | --interface )
            INTERFACE="$2"
            shift 2 ;;
        -matchstring | --matchstring )
            export MATCHSTRING="$2"
            shift 2 ;;
        -tftp | --tftp )
            export TFTP="$2"
            shift 2 ;;
        -i | --interactive )
            INTERACTIVE=true
            shift ;;
        -h | --help )
            show_help ;;
        * )
            print_error "Unknown option: $1"
            echo -e "  Run ${CYAN}$0 --help${RESET} for usage information."
            exit 1 ;;
    esac
done

