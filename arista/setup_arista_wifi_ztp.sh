# Input Validation (flag mode)
# ──────────────────────────────────────────────
if [[ -z "$IPVERSION" ]]; then
    print_error "IP version is required (-ipversion 4|6)"
    echo -e "  Run ${CYAN}$0 --help${RESET} or ${CYAN}$0 --interactive${RESET}"
    exit 1
fi

# ──────────────────────────────────────────────
# Test Mode
# ──────────────────────────────────────────────
if [[ "$MODE" == "test" ]]; then
    if [[ -z "$INTERFACE" ]]; then
        print_error "Test mode requires -interface"
        exit 1
    fi
    print_header "Testing DHCP and DNS"
    if ! command -v dhclient &>/dev/null; then
        print_error "dhclient is required. Install with: apt install isc-dhcp-client"
        exit 1
    fi
    print_success "dhclient found"

    if [[ "$IPVERSION" == "4" ]]; then
        print_header "DNS Lookup"
        nslookup "wifi-security-server"

        print_header "DHCP Test on ${INTERFACE}"
        timeout 5 tcpdump -c 2 -v -nni "$INTERFACE" port 68 and port 67 &
        timeout 5 dhclient -cf "${SCRIPT_DIR}/isc_dhcp_ap_client.conf" -d -v -sf /bin/true -lf /tmp/test.leases "$INTERFACE" 2>/dev/null

        if [[ -n "$CVCUE" ]]; then
            print_header "CV-CUE Connectivity"
            nc -zv "$CVCUE" 3851
        fi
    fi
    if [[ "$IPVERSION" == "6" ]]; then
        print_warn "IPv6 testing is not yet implemented."
    fi
    exit 0
fi

# ──────────────────────────────────────────────
# Auto-derive defaults & validate (generate/install)
# ──────────────────────────────────────────────
if [[ "$IPVERSION" == "4" ]]; then
    DHCPCONFIG="/etc/dhcp/dhcpd.conf"

    if [[ -n "$NETWORK" ]]; then
        local_prefix="${NETWORK##*/}"

        if [[ -z "$NETMASK" ]]; then
            NETMASK=$(cidr_to_netmask "$local_prefix")
            export NETMASK
        fi
        if [[ -z "$GATEWAY" ]]; then
            GATEWAY=$(suggest_gateway "$NETWORK")
            export GATEWAY
        fi
        if [[ -z "$RANGESTART" || -z "$RANGEEND" ]]; then
            range=$(suggest_range "$NETWORK")
            [[ -z "$RANGESTART" ]] && export RANGESTART="${range% *}"
            [[ -z "$RANGEEND" ]]   && export RANGEEND="${range#* }"
        fi
    fi

    if [[ -z "$MATCHSTRING" ]]; then
        export MATCHSTRING="ARISTA-AP*"
    fi

    missing=()
    [[ -z "$NETWORK" ]]    && missing+=("-network")
    [[ -z "$NETMASK" ]]    && missing+=("-netmask")
    [[ -z "$GATEWAY" ]]    && missing+=("-gateway")
    [[ -z "$RANGESTART" ]] && missing+=("-range-begin")
    [[ -z "$RANGEEND" ]]   && missing+=("-range-end")
    [[ -z "$NAMESERVER" ]] && missing+=("-nameserver")
    [[ -z "$CVCUE" ]]      && missing+=("-cvcue")

    if [[ ${#missing[@]} -gt 0 ]]; then
        print_error "Missing required options: ${missing[*]}"
        echo -e "  Run ${CYAN}$0 --help${RESET} for usage information."
        exit 1
    fi

    validate_cidr_v4 "$NETWORK"  || { print_error "Invalid IPv4 CIDR: $NETWORK"; exit 1; }
    validate_ipv4 "$NAMESERVER"  || { print_error "Invalid IPv4 nameserver: $NAMESERVER"; exit 1; }
    validate_ipv4 "$GATEWAY"     || { print_error "Invalid IPv4 gateway: $GATEWAY"; exit 1; }
    validate_ipv4 "$RANGESTART"  || { print_error "Invalid IPv4 range-begin: $RANGESTART"; exit 1; }
    validate_ipv4 "$RANGEEND"    || { print_error "Invalid IPv4 range-end: $RANGEEND"; exit 1; }
    validate_netmask "$NETMASK"  || { print_error "Invalid netmask: $NETMASK"; exit 1; }
fi

if [[ "$IPVERSION" == "6" ]]; then
    DHCPCONFIG="/etc/dhcp/dhcpd6.conf"

    if [[ -z "$MATCHSTRING" ]]; then
        export MATCHSTRING="ARISTA-AP-C-*"
    fi

    missing=()
    [[ -z "$NETWORK" ]]     && missing+=("-network")
    [[ -z "$NAMESERVER" ]]  && missing+=("-nameserver")
    [[ -z "$CVCUE" ]]       && missing+=("-cvcue")

    if [[ ${#missing[@]} -gt 0 ]]; then
        print_error "Missing required options: ${missing[*]}"
        echo -e "  Run ${CYAN}$0 --help${RESET} for usage information."
        exit 1
    fi

    export MAGICSTRING
    MAGICSTRING=$(python3 "${SCRIPT_DIR}/isc_dhcp6_generate_option17.py" "$CVCUE")
fi

# ──────────────────────────────────────────────
# Generate Mode
# ──────────────────────────────────────────────
if [[ "$MODE" == "generate" ]]; then
    ISCCONFIG=$(generate_config)
    print_header "Generated ISC DHCP Configuration"
    echo -e "${DIM}─────────────────────────────────────────────${RESET}"
    echo "$ISCCONFIG"
    echo -e "${DIM}─────────────────────────────────────────────${RESET}"
    print_success "Config printed to stdout. Copy the content above into ${CYAN}${DHCPCONFIG}${RESET}"
fi

# ──────────────────────────────────────────────
# Install Mode
# ──────────────────────────────────────────────
if [[ "$MODE" == "install" ]]; then
    ISCCONFIG=$(generate_config)

    print_header "Install Mode"

    if ! grep -q Ubuntu /etc/os-release 2>/dev/null; then
        print_error "Install mode is only supported on Ubuntu."
        exit 1
    fi
    print_success "Ubuntu detected"

    if ! command -v dhcpd &>/dev/null; then
        print_error "isc-dhcp-server is not installed. Run: apt install isc-dhcp-server"
        exit 1
    fi
    print_success "isc-dhcp-server found"

    if ! ip route get "$GATEWAY" &>/dev/null; then
        print_error "No interface in the target subnet. Ensure this server has an IP in ${NETWORK}."
        exit 1
    fi
    print_success "Interface reachable in target subnet"

    echo ""
    echo -e "${DIM}─────────────────────────────────────────────${RESET}"
    echo "$ISCCONFIG"
    echo -e "${DIM}─────────────────────────────────────────────${RESET}"
    echo ""
    print_warn "This will overwrite ${CYAN}${DHCPCONFIG}${RESET} and restart isc-dhcp-server."
    echo -en "  ${BOLD}Proceed?${RESET} ${DIM}[y/N]${RESET}: "
    read -r confirm
    if [[ ! "$confirm" =~ ^[Yy] ]]; then
        print_warn "Aborted."
        exit 0
    fi

    echo "$ISCCONFIG" | tee "$DHCPCONFIG" > /dev/null
    systemctl restart isc-dhcp-server.service
    print_success "Configuration written and isc-dhcp-server restarted."
    systemctl status isc-dhcp-server.service --no-pager -l
fi
